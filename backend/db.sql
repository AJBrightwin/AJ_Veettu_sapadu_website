BEGIN;

-- Enable UUID/cryptographic functions if needed
CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- 1. Categories
CREATE TABLE IF NOT EXISTS public.ajvs_category (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name_en VARCHAR(80) NOT NULL,
    name_ta VARCHAR(80) NOT NULL,
    slug VARCHAR(80) NOT NULL UNIQUE,
    sort_order BIGINT NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    art VARCHAR(10) NOT NULL,
    is_combo BOOLEAN NOT NULL DEFAULT FALSE,
    tagline_en VARCHAR(160) NOT NULL,
    tagline_ta VARCHAR(160) NOT NULL,
    theme VARCHAR(10) NOT NULL,
    image VARCHAR(100)
);

-- 2. Contact Messages
CREATE TABLE IF NOT EXISTS public.ajvs_contact_message (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    phone VARCHAR(15) NOT NULL,
    message TEXT NOT NULL,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    email VARCHAR(254) NOT NULL,
    reason VARCHAR(20) NOT NULL
);

-- 3. Coupons
CREATE TABLE IF NOT EXISTS public.ajvs_coupon (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(30) NOT NULL UNIQUE,
    description_en VARCHAR(150) NOT NULL,
    description_ta VARCHAR(150) NOT NULL,
    kind VARCHAR(10) NOT NULL,
    value NUMERIC NOT NULL CHECK (value >= 0),
    max_discount NUMERIC CHECK (max_discount IS NULL OR max_discount >= 0),
    min_order NUMERIC NOT NULL DEFAULT 0 CHECK (min_order >= 0),
    valid_from DATE,
    valid_until DATE,
    usage_limit BIGINT CHECK (usage_limit IS NULL OR usage_limit >= 0),
    once_per_phone BOOLEAN NOT NULL DEFAULT FALSE,
    used_count BIGINT NOT NULL DEFAULT 0 CHECK (used_count >= 0),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (valid_until IS NULL OR valid_from IS NULL OR valid_until >= valid_from)
);

-- 4. Delivery Areas
CREATE TABLE IF NOT EXISTS public.ajvs_delivery_area (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name_en VARCHAR(100) NOT NULL,
    name_ta VARCHAR(100) NOT NULL,
    delivery_fee NUMERIC NOT NULL DEFAULT 0 CHECK (delivery_fee >= 0),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    sort_order BIGINT NOT NULL DEFAULT 0 CHECK (sort_order >= 0)
);

-- 5. Dishes
CREATE TABLE IF NOT EXISTS public.ajvs_dish (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name_en VARCHAR(120) NOT NULL,
    name_ta VARCHAR(120) NOT NULL,
    description_en VARCHAR(300) NOT NULL,
    description_ta VARCHAR(300) NOT NULL,
    price NUMERIC NOT NULL CHECK (price >= 0),
    image VARCHAR(100),
    is_veg BOOLEAN NOT NULL DEFAULT TRUE,
    is_available BOOLEAN NOT NULL DEFAULT TRUE,
    is_special BOOLEAN NOT NULL DEFAULT FALSE,
    meal_slot VARCHAR(10) NOT NULL,
    sort_order BIGINT NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    category_id BIGINT NOT NULL,
    art VARCHAR(10) NOT NULL,
    badge VARCHAR(12) NOT NULL,
    compare_price NUMERIC CHECK (compare_price IS NULL OR compare_price >= 0),
    details_en TEXT NOT NULL,
    details_ta TEXT NOT NULL,
    spice_level SMALLINT NOT NULL DEFAULT 0 CHECK (spice_level >= 0),
    sunday_only BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT fk_ajvs_dish_category
        FOREIGN KEY (category_id)
        REFERENCES public.ajvs_category (id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

-- Helpful indexes
CREATE INDEX IF NOT EXISTS idx_ajvs_dish_category_id
    ON public.ajvs_dish (category_id);

CREATE INDEX IF NOT EXISTS idx_ajvs_dish_available
    ON public.ajvs_dish (is_available);

CREATE INDEX IF NOT EXISTS idx_ajvs_category_active_sort
    ON public.ajvs_category (is_active, sort_order);

CREATE INDEX IF NOT EXISTS idx_ajvs_contact_message_created
    ON public.ajvs_contact_message (created_at DESC);

COMMIT;

-- Verify that all five tables exist
SELECT table_name
FROM information_schema.tables
WHERE table_schema = 'public'
  AND table_name IN (
      'ajvs_category',
      'ajvs_contact_message',
      'ajvs_coupon',
      'ajvs_delivery_area',
      'ajvs_dish'
  )
ORDER BY table_name;